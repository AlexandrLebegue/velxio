"""Conversation-bound adapter to the same catalog/store/check/build MCP core.

Project identities stay on the server. The editor remains authoritative for
native circuit validation and compare-and-swap; source edits stay in cwd.
"""
import copy
import json
from pathlib import Path

from app.mcp.compact import ProjectStore, ProjectChecker, BuildService
from app.mcp.compact.arguments import normalize
from app.mcp.compact.facade import CompactRuntime
from .settings import AgentError
from .workspace import checked_document, project_revision


class ChatProjectService:
    def __init__(self, runtime, session):
        self.runtime, self.session = runtime, session
        self.store = ProjectStore(session.workspace.root / 'project-store', catalog=runtime.get_catalog(),
                                  max_storage_bytes=64 * 1024 * 1024)
        libraries, tools = CompactRuntime(None).inventories()
        self.checker = ProjectChecker(self.store, runtime.get_catalog(), inventory=libraries,
                                      source_root=Path(__file__).resolve().parents[3])
        self.editor_checker = ProjectChecker(self.store, runtime.get_catalog(), inventory=None,
                                      source_root=Path(__file__).resolve().parents[3])
        self.builds = BuildService(self.store, self.checker, toolchains=tools)
        self.current = None
        self.build_revisions = {}

    def restore_head(self, saved, document):
        # A candidate is published before the editor can inspect it. If the
        # editor refuses an update, restore the store head too; otherwise the
        # next ordinary save would fail its version comparison forever.
        if self.current and saved['project_id'] == self.current['project_id']:
            value = copy.deepcopy(document)
            for board in value['boards']:
                board.setdefault('libraries', [])
            restored = self.store.save_project(document=value, project_id=saved['project_id'], expected_version=saved['version'])
            self.current = {**restored, 'revision': project_revision(document)} if restored.get('ok') else None

    def snapshot(self):
        document = self.session.workspace.capture()
        revision = project_revision(document)
        self.session.workspace.commit(document)
        for board in document['boards']:
            board.setdefault('libraries', [])
        if not self.current or self.current['revision'] != revision:
            arguments = {'document': document}
            if self.current:
                arguments.update(project_id=self.current['project_id'], expected_version=self.current['version'])
            saved = self.store.save_project(**arguments)
            if not saved.get('ok'):
                return saved
            self.current = {**saved, 'revision': revision}
        return self.current

    async def save(self, arguments):
        arguments = normalize('save_project', arguments)
        current = self.session.workspace.capture()
        if 'from_example' not in arguments and not ('sketch' in arguments and not current['boards']):
            saved = self.snapshot()
            if not saved.get('ok'):
                return saved
            arguments = copy.deepcopy(arguments)
            if not any(key in arguments for key in ('document', 'sketch', 'changes')):
                # Native OpenCode edit tools already wrote the source in cwd.
                document = copy.deepcopy(current)
                if 'libraries' in arguments:
                    board = next(b for b in document['boards'] if b['id'] == document['activeBoardId'])
                    board['libraries'] = arguments.pop('libraries')
                arguments['document'] = document
            arguments.update(project_id=saved['project_id'], expected_version=saved['version'])
        saved = self.store.save_project(**arguments)
        if not saved.get('ok'):
            return saved
        # Read exactly the immutable version just generated by the shared core.
        with self.store._locked(False) as root:
            candidate = self.store._load_version(root, saved['project_id'], saved['version'])
        candidate = checked_document(candidate)
        previous = self.session.workspace.document
        previous_groups = copy.deepcopy(self.session.workspace.groups)
        try:
            result = await self.runtime.apply_candidate(self.session, candidate)
            if not result.get('ok'):
                self.restore_head(saved, current)
                return result
            # Only materialize after the editor has acknowledged this candidate.
            self.session.workspace.sync(self.session.workspace.document, self.session.workspace.revision)
        except BaseException:
            self.session.workspace.document = previous
            self.session.workspace.revision = project_revision(previous)
            self.session.workspace.groups = previous_groups
            self.restore_head(saved, current)
            raise
        # The editor may canonicalize native pin aliases. Persist that exact
        # normalized snapshot before check/build, rather than the pre-apply copy.
        document = self.session.workspace.capture()
        final = self.store.save_project(document=document, project_id=saved['project_id'], expected_version=saved['version'])
        if not final.get('ok'):
            return final
        self.current = {**final, 'revision': self.session.workspace.revision}
        board = next((b for b in document['boards'] if b['id'] == document['activeBoardId']), {})
        parts = [{'id':p['id'], 'metadataId':p['metadataId'],
                  'properties':{k:v for k,v in list(p.get('properties',{}).items())[:8]
                                if type(v) in (bool,int,float) or isinstance(v,str) and len(v)<=80}}
                 for p in document['components'][:8]]
        result = {'ok': True, 'saved': True, 'applied': True, 'validated': True,
                'project': {'board':board.get('boardKind'), 'components':parts,
                            'component_count':len(document['components']), 'connection_count':len(document['wires']),
                            'libraries':board.get('libraries', [])[:16], 'summary_only':True},
                'warnings': saved.get('warnings', []), 'workspace': self.runtime.source_context(self.session)}
        behavior = saved.get('example_provenance', {}).get('generated_behavior')
        if behavior and candidate['fileGroups'] == document['fileGroups']:
            result['generated_behavior'] = behavior
        while len(json.dumps(result, ensure_ascii=False).encode()) > 20 * 1024 and parts:
            parts.pop()
        result['project']['components_truncated'] = len(parts) != len(document['components'])
        result['project']['libraries_truncated'] = len(board.get('libraries', [])) > 16
        return result

    async def call(self, name, arguments):
        if not isinstance(arguments, dict):
            raise AgentError('invalid_argument', 'Send an argument object; the current project needs no ID.')
        if name == 'save_project':
            return await self.save(arguments)
        if name == 'read_artifact':
            return self.store.read_artifact(**arguments)
        saved = self.snapshot()
        if not saved.get('ok'):
            return saved
        # A chat call can never switch to another conversation's project.
        for field in ('project_id', 'version'):
            if field in arguments and arguments[field] != saved[field]:
                raise AgentError('revision_conflict', 'Use the current conversation: omit project_id and version; your source edits are preserved.')
        if name == 'check_project':
            if set(arguments) - {'project_id', 'version'}:
                raise AgentError('invalid_argument', 'Call check_project() with no arguments.')
            checker = self.editor_checker if self.session.editor_capabilities.get('compile') else self.checker
            result = checker.check_project(project_id=saved['project_id'], version=saved['version'])
            if result.get('ok'):
                issues = result['issues']
                result['informational_codes'] = sorted({i['code'] for i in issues if i['severity'] not in ('error','warning')})
                result['issues'] = [i for i in issues if i['severity'] in ('error','warning')]
                result['issues_truncated'] = result['issues_truncated'] or len(issues) != len(result['issues'])
            return {k: v for k, v in result.items() if k not in ('project_id', 'version')}
        if name == 'build_project':
            request = self.session.compile_request
            if request is None:
                raise AgentError('owner_integration_required', 'Start the turn through the authenticated chat API to compile.')
            from app.api.routes.compile import bind_compact_offline_owner
            self.builds.adapter = await bind_compact_offline_owner(request, self.session.compile_user)
            args = {k: v for k, v in arguments.items() if k not in ('project_id', 'version')}
            args.setdefault('action', 'start')
            if args['action'] == 'start':
                args.update(project_id=saved['project_id'], version=saved['version'])
            result = await self.builds.build_project(**args)
            if result.get('ok') and args['action'] == 'start':
                self.build_revisions[result['build_id']] = saved['revision']
            built_revision = self.build_revisions.get(result.get('build_id'))
            matches = built_revision == project_revision(self.session.workspace.capture())
            if result.get('ok') and result.get('state') in ('done','error','interrupted') and not matches:
                result['next_action'] = 'Current files differ from this build. Call build_project(action=start) for current files; do not claim this old build covers them.'
            return {**{k: v for k, v in result.items() if k not in ('project_id', 'version')},
                    'workspace_revision': built_revision,
                    'matches_current_workspace': matches,
                    'simulation_confirmed': False}
        raise AgentError('unknown_tool', 'Unknown conversation project operation')

    async def close(self):
        await self.builds.close()
